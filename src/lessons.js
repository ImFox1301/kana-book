// знаки урока (основные формы), в порядке таблицы
function lessonKana(l) {
  const out = [];
  for (const id of l.rows) { const r = ROWS.find(r => r.id === id); if (r) out.push(...r.h.split(' ')); }
  return (l.script === 'k' ? out.map(toKata) : out).concat(l.kana || []);
}
// знаки, которые пишутся в прописях (только одиночные основные, не сочетания)
function lessonWritable(l) { return lessonKana(l).filter(k => k.length === 1); }

if (typeof module !== 'undefined') module.exports = { LESSONS, lessonKana, lessonWritable };
